-- FLICKZ BY OSCAR — private gallery hardening migration
-- Run this in Supabase Dashboard > SQL Editor > New query.
-- It secures the existing tables and the already-created flickz-gallery bucket.

begin;

-- The gallery bucket must be private. Browsers receive only short-lived signed URLs.
update storage.buckets
set public = false,
    file_size_limit = 26214400,
    allowed_mime_types = array['image/jpeg','image/png','image/webp']
where id = 'flickz-gallery';

-- Record hashed client IPs only, never raw IP addresses, for code-guessing protection.
create table if not exists public.flickz_gallery_rate_limits (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);
create index if not exists flickz_gallery_rate_limits_ip_time_idx
  on public.flickz_gallery_rate_limits (ip_hash, created_at desc);
alter table public.flickz_gallery_rate_limits enable row level security;
revoke all on public.flickz_gallery_rate_limits from public, anon, authenticated;
grant all on public.flickz_gallery_rate_limits to service_role;
grant usage, select on sequence public.flickz_gallery_rate_limits_id_seq to service_role;

-- Existing admin policies on the gallery tables must remain owner-scoped.
alter table public.flickz_albums enable row level security;
alter table public.flickz_photos enable row level security;
alter table public.flickz_selections enable row level security;
alter table public.flickz_selections add column if not exists instagram_approved boolean not null default false;

drop policy if exists "Admins manage own albums" on public.flickz_albums;
create policy "Admins manage own albums"
on public.flickz_albums for all to authenticated
using (owner_id = auth.uid())
with check (owner_id = auth.uid());

drop policy if exists "Admins manage photos in own albums" on public.flickz_photos;
create policy "Admins manage photos in own albums"
on public.flickz_photos for all to authenticated
using (
  exists (
    select 1 from public.flickz_albums a
    where a.id = album_id and a.owner_id = auth.uid()
  )
)
with check (
  exists (
    select 1 from public.flickz_albums a
    where a.id = album_id and a.owner_id = auth.uid()
  )
);

drop policy if exists "Admins view selections for own albums" on public.flickz_selections;
create policy "Admins view selections for own albums"
on public.flickz_selections for select to authenticated
using (
  exists (
    select 1 from public.flickz_albums a
    where a.id = album_id and a.owner_id = auth.uid()
  )
);

drop policy if exists "Admins update selections for own albums" on public.flickz_selections;
create policy "Admins update selections for own albums"
on public.flickz_selections for update to authenticated
using (
  exists (
    select 1 from public.flickz_albums a
    where a.id = album_id and a.owner_id = auth.uid()
  )
)
with check (
  instagram_approved = false
  or (
    instagram_consent = true
    and exists (
      select 1 from public.flickz_albums a
      where a.id = album_id and a.owner_id = auth.uid()
    )
  )
);

-- Private Storage policies: an authenticated album owner can upload, preview, and delete
-- objects only inside the folder named with that album's UUID.
drop policy if exists "Admins upload to own album folders" on storage.objects;
create policy "Admins upload to own album folders"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'flickz-gallery'
  and exists (
    select 1 from public.flickz_albums a
    where a.id::text = (storage.foldername(name))[1]
      and a.owner_id = auth.uid()
  )
);

drop policy if exists "Admins read own album folders" on storage.objects;
create policy "Admins read own album folders"
on storage.objects for select to authenticated
using (
  bucket_id = 'flickz-gallery'
  and exists (
    select 1 from public.flickz_albums a
    where a.id::text = (storage.foldername(name))[1]
      and a.owner_id = auth.uid()
  )
);

drop policy if exists "Admins delete from own album folders" on storage.objects;
create policy "Admins delete from own album folders"
on storage.objects for delete to authenticated
using (
  bucket_id = 'flickz-gallery'
  and exists (
    select 1 from public.flickz_albums a
    where a.id::text = (storage.foldername(name))[1]
      and a.owner_id = auth.uid()
  )
);

-- Public visitors must not call the older direct lookup/selection RPCs.
-- The rate-limited Edge Function is now the only public client-gallery entry point.
revoke all on function public.flickz_lookup_gallery(text) from public, anon, authenticated;
revoke all on function public.flickz_submit_selection(text, uuid[], boolean) from public, anon, authenticated;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.flickz_albums to authenticated;
grant select, insert, update, delete on public.flickz_photos to authenticated;
grant select, update on public.flickz_selections to authenticated;

commit;

